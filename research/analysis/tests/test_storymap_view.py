"""Offline tests for the story-map viewer (storymap/view.py), on the synthetic W4 fixture.

Run from the repository root:
    PYTHONPATH=src .venv/bin/python -m unittest research.analysis.tests.test_storymap_view

The fixture (tests/fixtures/storymap/w4/, regenerated by its make_fixture.py) holds five invented
solvers: library copier, own idea then library, resisted the overseer then faked, stopped after an
overseer DM, never cheated. No network, no model calls.
"""
from __future__ import annotations

import contextlib
import io
import json
import re
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from research.analysis.storymap import view  # noqa: E402

FIX = HERE / "fixtures" / "storymap" / "w4"
SHARED = HERE / "fixtures" / "storymap"
AGENTS = [f"agent-00{n}" for n in range(1, 6)]


class ViewFixtureTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp())
        cls.out = cls.tmp / "out"
        cls.written = view.build(FIX / "map", FIX / "timeline", cls.out, taxonomy=None)
        cls.index = (cls.out / "index.html").read_text()
        cls.events = (cls.out / "events.html").read_text()
        cls.pages = {a: (cls.out / "agents" / f"{a}.html").read_text() for a in AGENTS}

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def test_writes_all_pages(self):
        self.assertEqual(len(self.written), 2 + len(AGENTS))
        for a in AGENTS:
            self.assertIn(f'data-agent="{a}"', self.index)
            self.assertIn(f'href="agents/{a}.html"', self.index)

    def test_index_filters_and_labels(self):
        row = lambda a: re.search(rf'<div class="row" data-agent="{a}"[^>]*>', self.index).group(0)  # noqa: E731
        self.assertIn('data-source="library"', row("agent-001"))
        self.assertIn('data-source="self_then_library"', row("agent-002"))
        self.assertIn('data-source="overseer_then_library"', row("agent-003"))
        self.assertIn('data-stopped="yes"', row("agent-004"))
        self.assertIn('data-faked="no"', row("agent-005"))
        self.assertIn('data-credited="no"', row("agent-003"))
        for name in ("source", "faked", "stopped", "credited"):
            self.assertIn(f'<select name="{name}">', self.index)
        # Phases as coloured spans; glyphs link into the agent page.
        self.assertIn('class="ph-faking"', self.index)
        self.assertIn('class="ph-stopped"', self.index)
        self.assertRegex(self.index, r'href="agents/agent-004\.html#sel=ev-\d+"')

    def test_agent_page_lanes_and_reaction(self):
        page = self.pages["agent-003"]
        for lane in ("Stance", "Library: event L1, L2", "Board/DMs: event B1, D1", "Submissions: event S1"):
            self.assertIn(f">{lane}</text>", page)
        for letter in view.LETTERS:
            self.assertIn(f">thought {letter}: codes</text>", page)
        # Event codes share names with thought codes: events are labelled "event B1", thoughts "thought B4".
        self.assertIn('<span class="badge">event B1</span>', page)
        self.assertIn("&middot; thought C6", page)
        self.assertIn('id="panel"', page)
        # Each clickable glyph has a matching article holding its content.
        keys = set(re.findall(r'class="g [^"]*" data-k="([^"]+)"', page))
        self.assertTrue(keys)
        for k in keys:
            self.assertIn(f'id="{k}"', page)
        # The revert event shows its stage-2 reaction (refake signal) and the thought quote.
        art = re.search(r'<article class="item k-fake" id="ev-\d+"><h3>145\.0 min.*?</article>', page, re.S).group(0)
        self.assertIn("reads the revert as a detector to evade", art)
        self.assertIn("refake_signal", art)
        self.assertIn("I&#x27;ll weaken it differently.", page)
        # A thought quoted by a reaction links back to that reaction.
        self.assertIn("Cited by the stage-2 reaction to", page)
        # Turning points are clickable.
        self.assertIn('class="tp" data-k="tp-0"', page)

    def test_text_is_escaped(self):
        page = self.pages["agent-003"]
        self.assertIn("&lt;frustrated&gt;", page)
        self.assertNotIn("<frustrated>", page)

    def test_events_page_breakdown(self):
        ev = self.events
        sec = re.search(r'<section class="ev" id="B1:post-000006">.*?</section>', ev, re.S).group(0)
        self.assertIn("3 reader(s)", sec)  # agents 003, 004, 005
        for a in ("agent-003", "agent-004", "agent-005"):
            self.assertIn(f'href="agents/{a}.html#sel=ev-', sec)
        # agent-003: belief/away; agent-004 and agent-005: none/neutral (2).
        cells = re.findall(r"<tr><th>(\w+)</th>(.*?)</tr>", sec)
        grid = {c: re.findall(r'<td class="n">(\d*)</td>', row) for c, row in cells}
        self.assertEqual(grid["belief"], ["", "1", "", ""])
        self.assertEqual(grid["none"], ["", "", "2", ""])
        lib = re.search(r'<section class="ev" id="L2:solutions/p07_shortcut\.lean">.*?</section>', ev, re.S).group(0)
        self.assertIn("3 reader(s)", lib)
        self.assertIn(">fake<", lib)
        self.assertIn('id="P2:sub-000131"', ev)
        self.assertIn('id="D1:dm-000012"', ev)
        self.assertNotIn('id="B1:post-000002"', ev)  # unrelated, no reaction: counted, not listed
        self.assertIn("1 unrelated board posts", ev)

    def test_offline_no_external_assets(self):
        for text in [self.index, self.events, *self.pages.values()]:
            for url in re.findall(r'(?:src|href)="(https?:[^"]+)"', text):
                self.assertTrue(url.startswith("https://fonts.googleapis.com"), url)
            self.assertIn('id="site-theme"', text)  # shared light/dark tokens
            self.assertIn("prefers-color-scheme:dark", text)

    def test_taxonomy_names(self):
        tax = self.tmp / "tax.md"
        tax.write_text("### C - Evaluation group (notes)\n### C4 - Some code. More text.\n### event L1 - listing\n")
        names = view.load_taxonomy(tax)
        self.assertEqual(names["C"], "Evaluation group")
        self.assertEqual(names["C4"], "Some code")
        self.assertNotIn("L1", names)
        self.assertEqual(view.load_taxonomy(self.tmp / "missing.md"), {})


class ViewPartialInputTest(unittest.TestCase):
    def test_timeline_only_and_wrapped_and_flat_dirs(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            mp = tmp / "map"
            (mp / "stage1").mkdir(parents=True)
            # Pipeline-wrapped stage-1 row, plus a malformed line.
            chunk = json.loads((FIX / "map" / "stage1" / "agent-002.jsonl").read_text().splitlines()[0])
            (mp / "stage1" / "agent-002.jsonl").write_text(json.dumps({"output": chunk, "to_t": 50}) + "\nnot json\n")
            flat = tmp / "flat"
            shutil.copytree(FIX / "timeline" / "timeline", flat)  # timeline DIR without timeline/ subdir
            view.build(mp, flat, tmp / "out", taxonomy=None)
            page = (tmp / "out" / "agents" / "agent-002.html").read_text()
            self.assertIn("Missing: stage 2, stage 3.", page)
            self.assertIn("stage-1 states (no stage 3)", page)
            self.assertIn("Malformed rows skipped", page)
            self.assertIn("no stage 3", (tmp / "out" / "index.html").read_text())
            self.assertTrue((tmp / "out" / "agents" / "agent-005.html").is_file())

    def test_cli(self):
        with tempfile.TemporaryDirectory() as tmp:
            with contextlib.redirect_stdout(io.StringIO()):
                rc = view.main(["--map", str(FIX / "map"), "--timeline", str(FIX / "timeline"), "--out", tmp,
                                "--taxonomy", str(Path(tmp) / "none.md")])
            self.assertEqual(rc, 0)
            self.assertTrue((Path(tmp) / "events.html").is_file())

    @unittest.skipUnless(any(SHARED.glob("**/index.json")) and any(
        p for p in SHARED.glob("**/agent-*.jsonl") if "w4" not in p.parts), "shared W1 fixture not present")
    def test_shared_w1_fixture(self):
        candidates = [p.parent for p in SHARED.glob("**/index.json") if "w4" not in p.parts]
        with tempfile.TemporaryDirectory() as tmp:
            for tdir in candidates:
                out = Path(tmp) / tdir.name
                view.build(Path(tmp) / "empty-map", tdir, out, taxonomy=None)
                self.assertTrue((out / "index.html").is_file())
                self.assertTrue((out / "events.html").is_file())


if __name__ == "__main__":
    unittest.main()
