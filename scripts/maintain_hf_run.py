#!/usr/bin/env python3
"""Narrow maintenance update of one already-published run in the private HF library.

docs/plan.md (October 17, 2026): behavior judge results for an already-published run reach
the library through a separately reviewed update that replaces only that run's
results.html, results.json and catalogue entry, adds its allowlisted judge files under
RUN/analysis/judge/ and updates archive-manifest.json digests for exactly those files.
Every other remote file is preserved byte for byte and no deletions are issued. Other
local differences (for example transcripts regenerated by a newer exporter) are reported
as skipped and never uploaded. publish_hf_library.py keeps refusing such changes.

--replace-judge (judge scope only) replaces the already-published judge outputs of the run with
another judge build (for example a re-run under a newer rubric), after a user decision: published
judge files that differ from the bundle are replaced instead of refused, new ones are added, and
their originals are backed up. A published judge file missing from the bundle is still refused
(nothing is deleted), and a replacement that HF would newly store as LFS is refused before any write.

--scope transcripts instead republishes regenerated transcript exports (for example the
October 18 full-history exports), after a user decision recorded in docs/plan.md: it replaces
only the run's existing RUN/transcripts/ files that differ from the bundle. The bundle's
transcript file set must equal the published one (nothing is added or deleted), the bundle's
catalogue entry must equal the published entry, the catalogue is not uploaded, and
archive-manifest.json changes only the digests of the replaced transcripts and total_bytes.
No transcript may be stored as LFS or named by an LFS rule, and no upload may come close to HF's
automatic LFS size. Every other local difference (reports, judge files) is reported as skipped.

--scope evaluator publishes independent-evaluator results of an already-published run, after a
user decision: it replaces the run's results.html and results.json, adds or replaces its
RUN/evaluations/ records, replaces the existing RUN/conference-view/ pages that the rebuilt
conference view changed (the bundle's conference file set must equal the published one, so
nothing there is added or deleted), regenerates the catalogue (only this run's entry may
change) and updates archive-manifest.json digests for exactly those files. As for transcripts,
no changed file may be stored as LFS or named by an LFS rule and .gitattributes must stay
unchanged. Every other local difference is reported as skipped and never uploaded.

--scope results replaces only the run's results.html and results.json (for example reports
regenerated by scripts/build_results.py) and regenerates the catalogue, where only this run's
entry may change; it is the evaluator scope without evaluator records or conference pages, with
the same no-LFS, unchanged-.gitattributes, guarded-batch, resume and verification rules.

--scope inspect repairs the hosted Inspect links of a published run: it replaces only
RUN/inspect-view/index.html (rebuilt with the current Space navigation, which lets Inspect View
follow HF's same-origin redirect of LFS-stored logs to its CDN) and rewrites the run's catalogue
'Inspect logs' link from the unlistable RUN/inspect/ directory to the published .eval file(s). The
new entry is the published entry with only those links changed (never the bundle's own entry), the
bundle's other Inspect View files must equal the published ones, and the rules of the results scope
apply otherwise.

--scope site regenerates the presentation of a published run with the current site generators
(owner request, October 21, 2026: run page summary card and tabs, shared light/dark theme, phone
layout, conference view without custom transcript links): it replaces only generated HTML/JSON views
that differ from the bundle, namely RUN/results.html, the existing RUN/conference-view/ pages and the
existing HTML pages of a published behavior judge build under RUN/analysis/judge/. It never changes
data: RUN/results.json and every non-HTML judge file must equal the published ones, the conference
and judge page sets must equal the published ones (nothing is added or deleted), and the catalogue
entry stays the published one (re-render the catalogue page first with --rerender-catalogue). Raw
records, Inspect logs and Inspect View, evaluator records and published transcript pages are never
touched. Otherwise the rules of the results scope apply (no LFS, unchanged .gitattributes, guarded
batches with the manifest last, backups, resume and verification).

--scope unlist (no --bundle) removes the run's row from the catalogue after the owner's request
(docs/plan.md, October 20, 2026) without deleting any file: the run must first be recorded in the
tracked data/library-unlisted.json. Exactly index.html, experiments.json and archive-manifest.json
change (the manifest records the run under unlisted_runs and keeps its files and digests); no
other file is added, removed or changed, no catalogue file may be stored as LFS, and the commit
is pinned to the planned revision. Removing the record and running publish/maintenance again
does not re-list a run automatically; re-listing is a separate, reviewed update.

Default: read-only plan pinned to the current Space revision. --commit first writes the
receipt, a before-inventory, backups of the originals and the plan, then uploads in guarded
batches (catalogue or manifest last), verifies the result against the original pre-maintenance
state and updates the receipt. After a failed or interrupted attempt, --resume-from names the first
attempt's backup directory, so that earlier commits are verified against that original state
instead of being accepted as the new starting point; a commit refuses to continue an already
partly applied update without it. Uses the operator's own HF SDK login; never loads a model
credential or starts an experiment.
"""
