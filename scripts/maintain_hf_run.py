def entry_diff(old, new):
    """Field-level summary of a catalogue entry change (links by name)."""
    diff = {key: {'old': old.get(key), 'new': new.get(key)}
            for key in sorted(set(old) | set(new)) if key != 'links' and old.get(key) != new.get(key)}
    old_links, new_links = old.get('links', {}), new.get('links', {})
    links = {'added': {k: v for k, v in new_links.items() if k not in old_links},
             'removed': {k: v for k, v in old_links.items() if k not in new_links},
             'changed': {k: {'old': old_links[k], 'new': v} for k, v in new_links.items()
                         if k in old_links and old_links[k] != v}}
    if any(links.values()):
        diff['links'] = links
    if old != new and not diff:
        diff['key_order'] = 'changed'
    return diff


def link_present(target, final_names, archive):
    """A catalogue link's target exists: a Space file (or folder), or a file the archive manifest records as
    moved to the private logs dataset (dataset_files) or kept offline (offline_files); the catalogue and run
    pages point those links at the dataset or at a "kept offline" notice."""
    if target.endswith('/'):
        return any(n.startswith(target) for n in final_names)
    archive = archive or {}
    return (target in final_names or target in (archive.get('dataset_files') or {})
            or target in (archive.get('offline_files') or {}))


def inspect_links_entry(entry, run, remote_names):
    """The published catalogue entry with only its Inspect log link(s) pointing at the published
    .eval files (a static host cannot list RUN/inspect/); other links keep their order."""
    prefix = run + '/' + INSPECT_LOGS_DIR
    logs = inspect_log_links(run, [n[len(prefix):] for n in remote_names if n.startswith(prefix)])
    if not logs:
        raise ValueError('The run has no published Inspect log under ' + prefix)
    links, placed = {}, False
    for label, target in entry['links'].items():
        if label == INSPECT_LOGS or label.startswith('Inspect log '):
            if not placed:
                links.update(logs)
                placed = True
        else:
            links[label] = target
    if not placed:
        links.update(logs)
    return {**entry, 'links': links}


def area(name, run):
    rest = name[len(run) + 1:] if name.startswith(run + '/') else name
    return rest.split('/')[0]


def check_outputs(bundle, receipt, backup_dir, commit, operation, resume_from=None):
    """Refuse output paths that could overwrite the bundle or earlier records, before anything
    is read from or written to the Space."""
    for path, label in ((receipt, 'receipt'), (backup_dir, 'backup directory')):
        if path is not None and bundle is not None and not outside(path, bundle):
            raise ValueError(f'The {label} must be outside the immutable prepared bundle')
    if commit and (receipt is None or backup_dir is None):
        raise ValueError('Committing a maintenance update requires a receipt and a backup directory')
    if commit and operation is None:
        raise ValueError('Committing requires a commit operation factory')
    if receipt is not None and Path(receipt).exists():
        raise ValueError('Receipt already exists; choose a new path (earlier receipts are preserved)')
    if backup_dir is not None and Path(backup_dir).exists() and (
            not Path(backup_dir).is_dir() or any(Path(backup_dir).iterdir())):
        raise ValueError('Backup directory must be new or empty (earlier backups are preserved)')
    if receipt is not None and backup_dir is not None:
        target, backups = Path(receipt).resolve(), Path(backup_dir).resolve()
        if target in (backups, backups / INVENTORY, backups / PLAN) or target.is_relative_to(backups / ORIGINAL):
            raise ValueError(f'The receipt must not replace the backup directory or its {INVENTORY}, '
                             f'{PLAN} or {ORIGINAL}/ copies')
    if resume_from is not None:
        if not Path(resume_from).is_dir():
            raise ValueError("--resume-from must be the first attempt's backup directory")
        for path, label in ((receipt, 'receipt'), (backup_dir, 'backup directory')):
            if path is not None and Path(path).resolve().is_relative_to(Path(resume_from).resolve()):
                raise ValueError(f"The {label} must be outside the resumed attempt's records (they are preserved)")


def load_origin(directory, repo, run, required, scope='judge', replace_judge=False):
    """The original pre-maintenance state recorded by the first attempt (--resume-from):
    its before-inventory and the original/ copies, each checked against that inventory.
    required(files) names the copies the first attempt saved besides .gitattributes."""
    directory = Path(directory)
    try:
        record = json.loads((directory / INVENTORY).read_text())
    except (OSError, ValueError) as error:
        raise ValueError(f"--resume-from needs the first attempt's backup directory with {INVENTORY}") from error
    if not isinstance(record, dict) or (record.get('operation'), record.get('repo'), record.get('run')) != (
            'maintain-run', repo, run):
        raise ValueError('The resumed records belong to another operation, repository or run')
    recorded = record.get('scope', 'judge')  # records written before scopes existed are judge records
    if recorded != scope:
        raise ValueError(f'The resumed records belong to the {recorded} scope, not the {scope} scope')
    if bool(record.get('replace_judge', False)) != bool(replace_judge):
        raise ValueError('The resumed records were written ' + ('with' if record.get('replace_judge') else 'without')
                         + ' --replace-judge; resume with the same mode')
    if record.get('origin_revision') != record.get('revision'):
        raise ValueError("Resume from the first attempt's backup directory, which holds the original "
                         'pre-maintenance state: ' + str(record.get('resume_from')))
    files = record.get('files')
    if not isinstance(files, dict) or not isinstance(record.get('revision'), str):
        raise ValueError('The resumed before-inventory is incomplete')
    originals = {}
    for name in [*required(files), ATTRIBUTES]:
        if name not in files:
            if name == ATTRIBUTES:
                continue
            raise ValueError('The original inventory lacks ' + name)
        path = directory / ORIGINAL / name
        data = path.read_bytes() if path.is_file() and not path.is_symlink() else None
        if data is None or not record_matches(data, files[name]):
            raise ValueError('Original backup missing or not matching the before-inventory: ' + name)
        originals[name] = data
    return {'revision': record['revision'], 'files': files, 'originals': originals}


def maintain_run(bundle, api, download, *, run, commit=False, repo=DEFAULT_REPO, receipt=None,
                 backup_dir=None, operation=None, resume_from=None, scope='judge', replace_judge=False):
    bundle = Path(bundle)
    if scope not in SCOPES or scope in NO_BUNDLE:
        raise ValueError('Unknown maintenance scope: ' + str(scope) + ' (unlist uses unlist_run, snapshots '
                         'archive_snapshots)')
    if scope == 'incident':
        raise ValueError('The incident scope uses maintain_incident')
    if replace_judge and scope != 'judge':
        raise ValueError('--replace-judge applies only to the judge scope')
    if run in unlisted_runs():
        raise ValueError('Run is unlisted by data/library-unlisted.json; its catalogue entry is not maintained: '
                         + str(run))
    judge_scope = scope == 'judge'
    inspect_scope = scope == 'inspect'
    site_scope = scope == 'site'  # presentation only: generated pages, never data or the catalogue entry
    results_scope = scope in ('results', 'inspect')  # inspect: the results scope with another report file
    evaluator_scope = scope in ('evaluator', 'results', 'inspect', 'site')  # results: without records or pages
    catalogue_scope = scope != 'transcripts'  # judge and evaluator: reports and the catalogue entry change
    if not isinstance(run, str) or not RUN_ID.fullmatch(run):
        raise ValueError('Invalid run ID')
    check_outputs(bundle, receipt, backup_dir, commit, operation, resume_from)
    manifest, incoming = load_bundle(bundle)
    if manifest['runs'] != [run] or [x['run'] for x in incoming] != [run]:
        raise ValueError('Maintenance needs a bundle prepared for exactly one run: ' + run)
    files = manifest['files']
    prefix = run + '/'
    replaceable = [prefix + name for name in ((INSPECT_PAGE,) if inspect_scope else REPLACEABLE)]
    if inspect_scope:
        page = bundle / replaceable[0]
        if not page.is_file() or INSPECT_REDIRECT_MARKER not in page.read_text(encoding='utf-8', errors='replace'):
            raise ValueError('The bundle has no Inspect View page built with the redirect-following Space '
                             'navigation: ' + replaceable[0])
    judge_pages = []  # site scope only
    if judge_scope:
        judge = sorted(name for name in files if name.startswith(prefix + JUDGE_PREFIX))
        for name in judge:
            if judge_excluded(name[len(prefix):]):
                raise ValueError('Bundle judge file outside the publication allowlist: ' + name)
        recorded = manifest.get('behavior_judge', {}).get(run)
        if (judge or recorded is not None) and (recorded or {}).get('included') != len(judge):
            raise ValueError('Bundle judge files do not match the preparation record')
        targets = set(replaceable) | set(judge)

        def required(original_files):  # --replace-judge: also every judge file the first attempt replaced
            return [*replaceable, *REGENERATED, MANIFEST,
                    *(name for name in (judge if replace_judge else []) if name in original_files
                      and not record_matches((bundle / name).read_bytes(), original_files[name]))]
    elif evaluator_scope:
        # Evaluator scope: the reports, the bundle's RUN/evaluations/ records and its
        # RUN/conference-view/ pages; everything else is an ordinary (skipped) bundle file.
        judge, recorded, transcripts = [], None, []
        evaluations = [] if results_scope or site_scope else sorted(
            name for name in files if name.startswith(prefix + EVALUATIONS_PREFIX))
        conference = [] if results_scope else sorted(
            name for name in files if name.startswith(prefix + CONFERENCE_PREFIX))
        # Site scope: the HTML pages of the bundle's judge build (its data files must equal the published ones).
        judge_pages = sorted(name for name in files if site_scope and name.startswith(prefix + JUDGE_PREFIX)
                             and name.endswith('.html'))
        if not evaluations and not results_scope and not site_scope:
            raise ValueError('The bundle has no evaluator records under ' + prefix + EVALUATIONS_PREFIX)
        if site_scope:
            for name in [replaceable[0], *(n for n in [*conference, *judge_pages] if n.endswith('.html'))]:
                text = (bundle / name).read_text(encoding='utf-8', errors='replace')
                if SITE_THEME_MARKER not in text:
                    raise ValueError('Site scope: a bundle page lacks the shared site theme (regenerate it with the '
                                     'current generators and prepare_hf_library.py): ' + name)
        targets = set(replaceable) | set(evaluations) | set(conference) | set(judge_pages)

        def required(original_files):  # the first attempt saved the reports and every file it replaced
            return [*replaceable, *REGENERATED, MANIFEST,
                    *(name for name in [*evaluations, *conference, *judge_pages] if name in original_files
                      and not record_matches((bundle / name).read_bytes(), original_files[name]))]
    else:
        # Transcripts scope: exactly the bundle's RUN/transcripts/ files; judge files and reports
        # are ordinary (skipped) bundle files here.
        judge, recorded = [], None
        transcripts = sorted(name for name in files if name.startswith(prefix + TRANSCRIPTS_PREFIX))
        targets = set(transcripts)

        def required(original_files):  # the first attempt saved every transcript it replaced
            return [*(name for name in transcripts if name in original_files
                      and not record_matches((bundle / name).read_bytes(), original_files[name])), MANIFEST]
    origin = (load_origin(resume_from, repo, run, required, scope, replace_judge)
              if resume_from is not None else None)

    info = hf_visibility.check(api.repo_info(repo, repo_type='space', files_metadata=True), repo, 'space')
    hf_visibility.check_dataset(api)  # the run's pages link to the private logs dataset
    base = info.sha
    remote = remote_files(api, repo, base)  # the current state is pinned to this revision
    current = inventory(remote)
    cache = {}

    def fetch(name, revision=base, listing=None):
        listing = remote if listing is None else listing
        if (name, revision) not in cache:
            data = Path(download(repo, name, repo_type='space', revision=revision)).read_bytes()
            if not matches(data, listing[name]):
                raise ValueError('Remote metadata mismatch: ' + name)
            cache[name, revision] = data
        return cache[name, revision]

    if not any(name.startswith(prefix) for name in remote):
        raise ValueError('Run is not published; use publish_hf_library.py for new runs: ' + run)
    for name in [*(replaceable if catalogue_scope else []), *REGENERATED, MANIFEST]:
        if name not in remote:
            raise ValueError('Remote file required for maintenance is missing: ' + name)
    if judge_scope:
        stale = sorted(n for n in remote if n.startswith(prefix + JUDGE_PREFIX) and n not in targets)
        if stale:
            raise ValueError(f'{len(stale)} published judge file(s) are not in the bundle (for example output '
                             'of another judge build); review them, nothing is deleted automatically: '
                             + ', '.join(stale[:EXAMPLES]))
    elif inspect_scope:
        # The published viewer must be the bundle's: only its index.html changes.
        viewer = prefix + INSPECT_VIEW
        published = {n for n in remote if n.startswith(viewer)}
        bundled = {n for n in files if n.startswith(viewer)}
        differing = sorted(n for n in bundled & published - set(replaceable)
                           if not matches((bundle / n).read_bytes(), remote[n]))
        if published != bundled or differing:
            raise ValueError(f'The Inspect View of the bundle and revision {base} differ beyond {replaceable[0]}; '
                             f'prepare the bundle with the viewer of the original publication: only in the bundle '
                             f'{sorted(bundled - published)[:EXAMPLES]}, only published '
                             f'{sorted(published - bundled)[:EXAMPLES]}, differing {differing[:EXAMPLES]}')
    elif results_scope:
        pass  # only the two reports are targets: no record or page set to compare
    elif evaluator_scope:
        if site_scope:
            # Presentation only: the report data and the judge build must be the published ones.
            data = prefix + 'results.json'
            if not matches((bundle / data).read_bytes(), remote[data]):
                raise ValueError(f'Site scope: {data} differs from revision {base}; this scope changes presentation '
                                 'only (use --scope results for regenerated report data)')
            published_judge = {n for n in remote if n.startswith(prefix + JUDGE_PREFIX)}
            bundled_judge = {n for n in files if n.startswith(prefix + JUDGE_PREFIX)}
            pages_differ = sorted({n for n in published_judge if n.endswith('.html')} ^ set(judge_pages))
            data_differ = sorted(n for n in published_judge if not n.endswith('.html') and (
                n not in bundled_judge or not matches((bundle / n).read_bytes(), remote[n])))
            if pages_differ or data_differ:
                raise ValueError(f'Site scope: the behavior judge build of the bundle and revision {base} differ; this '
                                 f'scope only restyles published judge pages: page sets differ {pages_differ[:EXAMPLES]}, '
                                 f'data files differ or missing {data_differ[:EXAMPLES]}')
        stale = [] if site_scope else sorted(  # site scope: evaluator records are not targets
            n for n in remote if n.startswith(prefix + EVALUATIONS_PREFIX) and n not in targets)
        if stale:
            raise ValueError(f'{len(stale)} published evaluator record(s) are not in the bundle; review them, '
                             'nothing is deleted automatically: ' + ', '.join(stale[:EXAMPLES]))
        published = {n for n in remote if n.startswith(prefix + CONFERENCE_PREFIX)}
        only_bundle, only_remote = sorted(set(conference) - published), sorted(published - set(conference))
        if only_bundle or only_remote:
            raise ValueError(f'The conference-view file sets of the bundle and revision {base} differ; this scope '
                             f'only replaces existing conference pages and adds or deletes none: only in the bundle '
                             f'{only_bundle[:EXAMPLES]}, only published {only_remote[:EXAMPLES]}')
    else:
        published = {n for n in remote if n.startswith(prefix + TRANSCRIPTS_PREFIX)}
        only_bundle, only_remote = sorted(targets - published), sorted(published - targets)
        if only_bundle or only_remote:
            raise ValueError(f'The transcript file sets of the bundle and revision {base} differ; this scope '
                             f'only replaces existing transcripts and adds or deletes nothing: only in the bundle '
                             f'{only_bundle[:EXAMPLES]}, only published {only_remote[:EXAMPLES]}')

    # The original pre-maintenance state: this revision, or the first attempt's records when
    # resuming, so that changes made by earlier attempts are verified rather than trusted.
    if origin is None:
        origin_revision, origin_files = base, current

        def original(name):
            return fetch(name) if name in remote else b''
    else:
        origin_revision, origin_files = origin['revision'], origin['files']

        def original(name):
            return origin['originals'].get(name, b'')
    if replace_judge and not any(n.startswith(prefix + JUDGE_PREFIX) for n in origin_files):
        raise ValueError(f'No published judge files to replace at revision {origin_revision}; publish them with '
                         'the judge scope without --replace-judge')

    def catalogue(index_bytes, html, manifest_bytes, label):
        index, archive = json.loads(index_bytes), json.loads(manifest_bytes)
        if index.get('warnings') or archive.get('warnings'):
            raise ValueError(f'{label} catalogue or manifest has warnings; review before maintenance')
        if archive.get('schema') != 'gdm-private-space/1' or run not in archive.get('runs', []):
            raise ValueError(f'{label} archive manifest does not list the run: ' + run)
        listed = [x.get('run') for x in index.get('experiments', [])]
        if listed.count(run) != 1 or len(set(listed)) != len(listed):
            raise ValueError(f'{label} catalogue must list the run exactly once among unique entries')
        # The current generator must reproduce the catalogue byte for byte from its own entries,
        # so regenerating it cannot alter any other entry or row (the transcripts scope never
        # regenerates it).
        if catalogue_scope and regenerate(index['experiments']) != {'experiments.json': index_bytes, 'index.html': html}:
            raise ValueError(f'The current generator does not reproduce the {label.lower()} catalogue byte for '
                             'byte; regenerating it would change other catalogue entries')
        return index, archive

    current_index, current_archive = catalogue(fetch('experiments.json'), fetch('index.html'), fetch(MANIFEST),
                                               'Remote')
    if origin is None:
        old_index, old_archive = current_index, current_archive
    else:
        # Transcripts scope: the catalogue is not a target, so verify() below requires its
        # original blobs; only the manifest has an original copy.
        old_index, old_archive = catalogue(
            *((original('experiments.json'), original('index.html')) if catalogue_scope
              else (fetch('experiments.json'), fetch('index.html'))), original(MANIFEST), 'Original')
        if others(current_index, run) != others(old_index, run):
            raise ValueError('Another catalogue entry changed since the original revision ' + origin_revision)
        changeable = targets | (set(REGENERATED) if catalogue_scope else set())

        def unrelated(archive):
            return ({k: v for k, v in archive.items() if k not in ('files', 'total_bytes')},
                    {n: d for n, d in archive['files'].items() if n not in changeable})
        if unrelated(current_archive) != unrelated(old_archive):
            raise ValueError('The archive manifest changed outside the maintenance since the original revision '
                             + origin_revision)

    # Catalogue: only the run's entry changes, relative to the original catalogue.
    old_entries = old_index['experiments']
    old_entry = next(x for x in old_entries if x['run'] == run)
    current_entry = next(x for x in current_index['experiments'] if x['run'] == run)
    if inspect_scope:  # never the bundle's own entry, which may have drifted from the published one
        incoming = [inspect_links_entry(old_entry, run, remote)]
    elif site_scope:  # the published entry, unchanged (the catalogue page reads newer fields itself)
        incoming = [old_entry]
    if catalogue_scope:
        regenerated = regenerate(merge_entries(others(old_index, run), incoming))
        new_index = json.loads(regenerated['experiments.json'])
        if (set(new_index) != set(old_index) or others(new_index, run) != others(old_index, run)
                or [x['run'] for x in new_index['experiments']].count(run) != 1
                or len(new_index['experiments']) != len(old_entries)):
            raise ValueError('Another catalogue entry would change')
    else:
        regenerated = {}  # index.html and experiments.json stay byte for byte as published
        # An entry published before the catalogue summary existed (October 21, 2026) is compared
        # without the bundle's derived summary: this scope leaves the catalogue unchanged either way.
        if (incoming[0] if 'summary' in current_entry else without_summary(incoming[0])) != current_entry:
            raise ValueError(f"The bundle's catalogue entry for {run} differs from the published entry, but the "
                             'transcripts scope never changes the catalogue: '
                             + json.dumps(entry_diff(current_entry, incoming[0]), sort_keys=True))

    # Run files: exactly results.html/results.json may be replaced; allowlisted judge files
    # may be added. An existing judge file must already be identical (resume).
    # Transcripts scope: exactly the existing transcripts that differ are replaced.
    # Evaluator scope: the reports, the conference pages and the published evaluator records that
    # differ are replaced; evaluator records absent remotely are added.
    replacements, replacement_identical, additions, judge_present = [], [], [], []
    if judge_scope:
        replace_names = replaceable
    elif evaluator_scope:
        replace_names = [*replaceable, *conference, *judge_pages, *(n for n in evaluations if n in remote)]
    else:
        replace_names = transcripts
    for name in replace_names:
        if matches((bundle / name).read_bytes(), remote[name]):
            replacement_identical.append(name)
        else:
            replacements.append((name, bundle / name))
    for name in judge:
        if name in remote:
            if matches((bundle / name).read_bytes(), remote[name]):
                judge_present.append(name)
            elif replace_judge:  # another judge build: replaced, its original backed up
                replacements.append((name, bundle / name))
            else:
                raise ValueError('Published judge file differs from the bundle: ' + name)
        else:
            additions.append((name, bundle / name))
    if evaluator_scope:
        additions += [(name, bundle / name) for name in evaluations if name not in remote]
    addable = judge if judge_scope else evaluations if evaluator_scope else []
    added = [name for name in addable if name not in origin_files]  # cumulative, relative to the original
    if catalogue_scope:
        replaced = [name for name in (
            [*replaceable, *(n for n in judge if replace_judge and n in origin_files)] if judge_scope else
            [*replaceable, *conference, *judge_pages, *(n for n in evaluations if n in origin_files)])
                    if not record_matches((bundle / name).read_bytes(), origin_files[name])]
    else:  # a transcript missing from the original inventory is refused by verify() below
        replaced = [name for name in transcripts if name not in origin_files
                    or not record_matches((bundle / name).read_bytes(), origin_files[name])]
    final_names = set(remote) | targets
    for label, target in incoming[0]['links'].items():
        if not link_present(target, final_names, old_archive):
            raise ValueError(f'Catalogue link {label} would point to a missing file: {target}')

    # Everything else stays as published: report local differences, never upload them.
    skipped, unchanged = [], 0
    for name in sorted(files):
        if name in targets or name in REGENERATED:
            continue
        if name not in remote:
            skipped.append({'path': name, 'reason': 'absent_remotely'})
        elif not matches((bundle / name).read_bytes(), remote[name]):
            skipped.append({'path': name, 'reason': 'differs_from_remote'})
        else:
            unchanged += 1
    by_area = {}
    for row in skipped:
        key = area(row['path'], run)
        by_area[key] = by_area.get(key, 0) + 1
    remote_only = sorted(n for n in remote if n.startswith(prefix) and n not in files)

    old_files = old_archive['files']
    new_files = dict(old_files)
    if catalogue_scope:
        for name in sorted(targets):
            new_files[name] = files[name]  # verified against the bundle bytes by load_bundle
        for name in REGENERATED:
            new_files[name] = digest(regenerated[name])
    else:
        unrecorded = sorted(set(replaced) - set(old_files))
        if unrecorded:
            raise ValueError('The original archive manifest has no record of replaced transcript(s); this scope '
                             'only updates existing digests: ' + ', '.join(unrecorded[:EXAMPLES]))
        for name in replaced:  # exactly the replaced transcripts, relative to the original
            new_files[name] = files[name]
    new_manifest = {**old_archive, 'files': new_files,
                    'total_bytes': sum(x['bytes'] for x in new_files.values())}
    manifest_bytes = json.dumps(new_manifest, indent=2).encode()
    if not judge_scope and new_manifest == current_archive:
        manifest_bytes = fetch(MANIFEST)  # nothing left to record: keep the published bytes
    planned_root = {**regenerated, MANIFEST: manifest_bytes}
    root_uploads = [(n, d) for n, d in planned_root.items() if not matches(d, remote[n])]
    # Judge files (added, then replaced) before the reports that link them.
    uploads = (additions + [r for r in replacements if r[0] not in replaceable]
               + [r for r in replacements if r[0] in replaceable])
    allowed = targets | (set(REGENERATED) if catalogue_scope else set()) | {MANIFEST}
    if any(name not in allowed for name, _ in uploads + root_uploads):
        raise ValueError('Planned upload outside the maintenance allowlist')
    in_dataset = sorted(name for name, _ in uploads if name in old_archive.get('dataset_files', {}))
    if in_dataset:  # moved to the private logs dataset (--scope migrate-logs); never re-added to the Space
        raise ValueError('Planned upload of file(s) now kept in the logs dataset: ' + ', '.join(in_dataset[:EXAMPLES]))
    expected = {**{name: bundle / name for name in sorted(targets)}, **planned_root}

    def verify(listing, revision, complete):
        """Compare a remote state with the original inventory: only planned files may differ or
        be added and .gitattributes may gain only exact LFS rules for added judge files.
        complete=True also requires every planned file with exactly its planned content.
        Transcripts scope: no file may be added or removed and .gitattributes must not change."""
        state = inventory(listing)
        if evaluator_scope:
            return verify_evaluator(state, listing, complete)
        if not judge_scope:
            return verify_transcripts(state, listing, complete)
        missing = sorted((set(origin_files) | (set(added) if complete else set())) - set(state))
        unexpected = sorted(set(state) - set(origin_files) - set(added) - {ATTRIBUTES})
        if missing or unexpected:
            raise ValueError(f'Remote file inventory changed unexpectedly relative to the original revision '
                             f'{origin_revision}: missing {missing[:EXAMPLES]}, unexpected {unexpected[:EXAMPLES]}')
        attributes = 'unchanged'
        if ATTRIBUTES in state and (ATTRIBUTES not in origin_files
                                    or not same(origin_files[ATTRIBUTES], state[ATTRIBUTES])):
            validate_lfs_additions(original(ATTRIBUTES), fetch(ATTRIBUTES, revision, listing), {run},
                                   set(added), listing)
            attributes = 'exact LFS additions for newly added judge files'
        for name in sorted(origin_files):
            if name not in expected and name != ATTRIBUTES and not same(origin_files[name], state[name]):
                raise ValueError('Unrelated remote file changed: ' + name)
        if complete:
            for name, data in expected.items():
                if not matches(payload(data), listing[name]):
                    raise ValueError('File hash mismatch after maintenance: ' + name)
        return attributes

    def verify_transcripts(state, listing, complete):
        # No transcript may be stored as LFS, in this state or in the original one (none of the
        # published transcripts were LFS, and HF serves LFS-tracked HTML as a download). Absolute,
        # not relative to the original revision, so a fresh attempt after a failed one cannot
        # accept a transcript an earlier attempt left in LFS.
        stored_lfs = sorted(n for n in targets if (n in state and state[n]['lfs_sha256'])
                            or (origin_files.get(n) or {}).get('lfs_sha256'))
        if stored_lfs:
            raise ValueError('Published transcript(s) stored as LFS, but the transcripts scope uploads only regular '
                             'files and adds no LFS rule; neither a fresh attempt nor --resume-from can continue, '
                             'repair the Space manually first: ' + ', '.join(stored_lfs[:EXAMPLES]))
        if (ATTRIBUTES in state) != (ATTRIBUTES in origin_files) or (
                ATTRIBUTES in state and not same(origin_files[ATTRIBUTES], state[ATTRIBUTES])):
            raise ValueError(f'{ATTRIBUTES} changed relative to the original revision {origin_revision}, but the '
                             'transcripts scope adds no LFS rule (was a replaced transcript stored as LFS?)')
        missing, unexpected = sorted(set(origin_files) - set(state)), sorted(set(state) - set(origin_files))
        if missing or unexpected:
            raise ValueError(f'Remote file inventory changed unexpectedly relative to the original revision '
                             f'{origin_revision}: missing {missing[:EXAMPLES]}, unexpected {unexpected[:EXAMPLES]}')
        for name in sorted(origin_files):
            if name not in expected and not same(origin_files[name], state[name]):
                raise ValueError('Unrelated remote file changed: ' + name)
        if complete:
            for name, data in expected.items():
                if not matches(payload(data), listing[name]):
                    raise ValueError('File hash mismatch after maintenance: ' + name)
        return 'unchanged'

    def verify_evaluator(state, listing, complete):
        # No changed run file may be stored as LFS (HF serves LFS-tracked HTML as a download) and
        # .gitattributes must not change; only the evaluator records may be added.
        changed = sorted({*replaced, *added, *(n for n, _ in replacements + additions)})
        stored_lfs = sorted(n for n in changed if n in state and state[n]['lfs_sha256'])
        if stored_lfs:
            raise ValueError('Planned file(s) stored as LFS, but the evaluator scope uploads only regular files and '
                             'adds no LFS rule; repair the Space manually first: ' + ', '.join(stored_lfs[:EXAMPLES]))
        if (ATTRIBUTES in state) != (ATTRIBUTES in origin_files) or (
                ATTRIBUTES in state and not same(origin_files[ATTRIBUTES], state[ATTRIBUTES])):
            raise ValueError(f'{ATTRIBUTES} changed relative to the original revision {origin_revision}, but the '
                             'evaluator scope adds no LFS rule (was a planned file stored as LFS?)')
        missing = sorted((set(origin_files) | (set(added) if complete else set())) - set(state))
        unexpected = sorted(set(state) - set(origin_files) - set(added))
        if missing or unexpected:
            raise ValueError(f'Remote file inventory changed unexpectedly relative to the original revision '
                             f'{origin_revision}: missing {missing[:EXAMPLES]}, unexpected {unexpected[:EXAMPLES]}')
        for name in sorted(origin_files):
            if name not in expected and not same(origin_files[name], state[name]):
                raise ValueError('Unrelated remote file changed: ' + name)
        if complete:
            for name, data in expected.items():
                if not matches(payload(data), listing[name]):
                    raise ValueError('File hash mismatch after maintenance: ' + name)
        return 'unchanged'

    verify(remote, base, complete=False)  # earlier attempts' commits, when resuming
    if evaluator_scope:
        # Before any write: no run upload may meet an LFS rule or come close to HF's automatic LFS size.
        names = sorted(n for n, _ in replacements + additions)
        ruled = lfs_rule_matches(fetch(ATTRIBUTES), names) if ATTRIBUTES in remote else []
        if ruled:
            raise ValueError(f'LFS rule(s) in {ATTRIBUTES} at revision {base} match planned upload(s), so HF would '
                             'store them as LFS; the evaluator scope uploads only regular files, repair the rules '
                             'first: ' + ', '.join(ruled[:EXAMPLES]))
        large = [f'{n} ({files[n]["bytes"]} bytes)' for n in names if files[n]['bytes'] >= LFS_SAFE_BYTES]
        if large:
            raise ValueError(f'File(s) to upload at or above {LFS_SAFE_BYTES} bytes, close to the size HF stores as '
                             'LFS, which the evaluator scope does not allow: ' + ', '.join(large[:EXAMPLES]))
    elif not judge_scope:
        # Before any write: no upload may meet an LFS rule or come close to HF's automatic LFS size.
        ruled = lfs_rule_matches(fetch(ATTRIBUTES), transcripts) if ATTRIBUTES in remote else []
        if ruled:
            raise ValueError(f'LFS rule(s) in {ATTRIBUTES} at revision {base} match published transcript(s), so HF '
                             'would store their replacements as LFS; the transcripts scope uploads only regular '
                             'files, repair the rules first: ' + ', '.join(ruled[:EXAMPLES]))
        large = [f'{n} ({files[n]["bytes"]} bytes)' for n, _ in replacements if files[n]['bytes'] >= LFS_SAFE_BYTES]
        if large:
            raise ValueError(f'Transcript(s) to upload at or above {LFS_SAFE_BYTES} bytes, close to the size HF stores '
                             'as LFS, which the transcripts scope does not allow: ' + ', '.join(large[:EXAMPLES]))
    elif replace_judge:
        # Before any write: HF would store a large replacement of a regular judge file as LFS and add a rule
        # for it, which verification only allows for added judge files. A file an LFS rule already names
        # stays LFS with an unchanged .gitattributes.
        names = sorted(n for n, _ in replacements if n.startswith(prefix + JUDGE_PREFIX))
        ruled = set(lfs_rule_matches(fetch(ATTRIBUTES), names)) if ATTRIBUTES in remote else set()
        large = [f'{n} ({files[n]["bytes"]} bytes)' for n in names
                 if n not in ruled and files[n]['bytes'] >= LFS_SAFE_BYTES]
        if large:
            raise ValueError(f'Judge file replacement(s) at or above {LFS_SAFE_BYTES} bytes, which HF would newly '
                             'store as LFS: ' + ', '.join(large[:EXAMPLES]))
    if judge_scope and replace_judge:
        # The catalogue and manifest are committed last, so a published target whose bytes differ from the
        # published manifest's record for it (or that the manifest does not record, such as an added judge
        # file) was uploaded by an earlier, interrupted attempt. Files equal to the bundle have its digest.
        def published_digest(name):
            return files[name] if matches((bundle / name).read_bytes(), remote[name]) else digest(fetch(name))
        already_applied = [n for n in sorted(targets) if n in remote
                           and current_archive['files'].get(n) != published_digest(n)]
        reason = (': published files that differ from the record of the published archive manifest, which is '
                  'uploaded last; without an earlier attempt, review the manifest')
    elif judge_scope:
        # Every judge file is committed before either report and the catalogue last, so a published
        # judge file or the bundle's catalogue entry shows an earlier, partly applied attempt.
        # Without judge files an identical report is the only sign.
        already_applied = [*judge_present, *(['experiments.json'] if current_entry == incoming[0] else []),
                           *([] if judge else replacement_identical)]
        reason = ''
    elif evaluator_scope:
        # The catalogue and manifest are committed last, in one batch, so a published target whose bytes
        # differ from the published manifest's record for it (or that the manifest does not record) was
        # uploaded by an earlier, interrupted attempt. Pages equal to the bundle have the bundle's digest.
        def published_digest(name):
            return files[name] if matches((bundle / name).read_bytes(), remote[name]) else digest(fetch(name))
        already_applied = [n for n in sorted(targets) if n in remote
                           and current_archive['files'].get(n) != published_digest(n)]
        reason = (': published files that differ from the record of the published archive manifest, which is '
                  'uploaded last; without an earlier attempt, review the manifest')
    else:
        # The manifest is committed last, so a published transcript whose bytes differ from the published
        # manifest's record for it was uploaded by an earlier, interrupted attempt, whatever the current
        # bundle holds (the exporter may have been rerun since). A page equal to the bundle has the
        # bundle's digest; every other page is downloaded (and kept for the backups) and digested.
        def published_digest(name):
            return files[name] if name in replacement_identical else digest(fetch(name))
        already_applied = [n for n in transcripts if current_archive['files'].get(n) != published_digest(n)]
        reason = (': published transcripts that differ from the record of the published archive manifest, which '
                  'is uploaded last; without an earlier attempt, review the manifest')
    if commit and origin is None and already_applied:
        raise ValueError(f'The maintenance is already partly applied at revision {base} ({len(already_applied)} '
                         f"file(s){reason}); rerun with --resume-from set to the first attempt's backup directory "
                         'so the result is verified against the original pre-maintenance state')
    if commit and origin is None and (replace_judge or not judge_scope) and not uploads + root_uploads:
        raise ValueError(f'Nothing to upload at revision {base}: every planned file already equals the bundle and '
                         'the archive manifest records it, so no commit is made; to verify an earlier attempt '
                         "against its original state, rerun with --resume-from set to the first attempt's backup "
                         'directory')

    result = {
        'operation': 'maintain-run', 'scope': scope, **({'replace_judge': True} if replace_judge else {}),
        'repo': repo, **hf_visibility.record(repo, 'space'), 'run': run,
        'origin_revision': origin_revision, 'base_revision': base,
        'resume_from': None if resume_from is None else str(resume_from), 'committed': False,
        'replaced': replaced, 'added': added,
        **({} if catalogue_scope else {'replaced_sizes': [
            {'path': n, 'old_bytes': origin_files.get(n, {}).get('size'), 'new_bytes': files[n]['bytes']}
            for n in replaced]}),
        'to_replace': [n for n, _ in replacements], 'to_add': [n for n, _ in additions],
        'replacement_identical': replacement_identical,
        **({'judge_already_present': judge_present} if judge_scope else {}),
        'already_applied': already_applied, 'resume_required': bool(already_applied) and origin is None,
        **({'evaluator': {
            'evaluation_files': len(evaluations), 'evaluation_files_added': len(added),
            'conference_view': {'files': len(conference), 'file_sets_equal': True,
                                'replaced': sum(n.startswith(prefix + CONFERENCE_PREFIX) for n in replaced)},
            **({'judge_pages': {'files': len(judge_pages), 'file_sets_equal': True,
                                'replaced': sum(n in judge_pages for n in replaced)},
                'results_json_unchanged': True} if site_scope else {}),
            'largest_upload_bytes': max([files[n]['bytes'] for n, _ in replacements + additions] or [0]),
            'lfs_safe_limit_bytes': LFS_SAFE_BYTES}} if evaluator_scope else {}),
        **({} if catalogue_scope else {
            'transcripts': {'files': len(transcripts), 'file_sets_equal': True,
                            'largest_new_bytes': max(files[n]['bytes'] for n in transcripts),
                            'lfs_safe_limit_bytes': LFS_SAFE_BYTES},
            'catalogue_unchanged': True}),
        'catalogue': {'files': [n for n, _ in root_uploads] if catalogue_scope else [],
                      'entry_diff': entry_diff(old_entry, incoming[0]),
                      'other_entries_unchanged': len(old_entries) - 1,
                      **({'remote_catalogue_reproduced': True} if catalogue_scope else {})},
        'archive_manifest': {'changed_digests': sorted(n for n in new_files if old_files.get(n) != new_files[n]),
                             'total_bytes_before': old_archive.get('total_bytes'),
                             'total_bytes_after': new_manifest['total_bytes'],
                             **({} if catalogue_scope else {'upload': bool(root_uploads)})},
        'skipped_local_differences': {
            'count': len(skipped),
            'differs_from_remote': sum(r['reason'] == 'differs_from_remote' for r in skipped),
            'absent_remotely': sum(r['reason'] == 'absent_remotely' for r in skipped),
            'by_area': by_area, 'names': skipped[:EXAMPLES], 'truncated': len(skipped) > EXAMPLES},
        'unchanged_bundle_files': unchanged,
        'remote_only_preserved': {'count': len(remote_only), 'names': remote_only[:EXAMPLES]},
        **({'local_judge_exclusions': len((recorded or {}).get('excluded', []))} if judge_scope else {}),
        'uploads': len(uploads) + len(root_uploads),
    }
    if not commit:
        return result

    backup_dir, receipt = Path(backup_dir), Path(receipt)
    revision, committed_batches = base, 0

    def write_receipt(status):
        write_json(receipt, {**result, 'last_revision': revision, 'committed_batches': committed_batches,
                             'status': status})
    receipt.parent.mkdir(parents=True, exist_ok=True)
    write_receipt('writing backups; nothing uploaded')  # an unwritable receipt fails before any upload
    try:
        backup_dir.mkdir(parents=True, exist_ok=True)
        write_json(backup_dir / INVENTORY, {'operation': 'maintain-run', 'scope': scope,
                                            **({'replace_judge': True} if replace_judge else {}),
                                            'repo': repo, 'run': run,
                                            'revision': base, 'origin_revision': origin_revision,
                                            'resume_from': result['resume_from'], 'files': current})
        saved = [*([*replaceable, *REGENERATED, *(n for n, _ in replacements if n not in replaceable)]
                   if judge_scope else
                   sorted({*replaceable, *REGENERATED, *(n for n, _ in replacements)}) if evaluator_scope
                   else [n for n, _ in replacements]), MANIFEST,
                 *([ATTRIBUTES] if ATTRIBUTES in remote else [])]
        for name in saved:
            target = backup_dir / ORIGINAL / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(fetch(name))
        write_json(backup_dir / PLAN, result)
        result.update(backup_dir=str(backup_dir), backups=sorted(saved))
        write_receipt('backups written; nothing uploaded')
        planned_batches = [*batches(uploads)]
        for number, batch in enumerate([*planned_batches, *([root_uploads] if root_uploads else [])]):
            latest = api.repo_info(repo, repo_type='space')
            if not hf_visibility.unchanged(latest, repo, 'space', revision):
                raise ValueError('Space changed concurrently or its visibility differs from the record; rerun the dry run '
                                 'against the latest revision')
            response = space_commit(api, 
                repo_id=repo, repo_type='space', parent_commit=revision,
                commit_message='Maintenance update of ' + run + (
                    ': results and replaced behavior judge outputs' if replace_judge else
                    ': results and behavior judge outputs' if judge_scope else
                    ': Inspect View log loading and Inspect log links' if inspect_scope else
                    ': regenerated site pages (presentation only)' if site_scope else
                    ': regenerated results report' if results_scope else
                    ': results and independent evaluator outputs' if evaluator_scope else
                    ': regenerated transcript exports'),
                operations=[operation(path_in_repo=n, path_or_fileobj=str(d) if isinstance(d, Path) else d)
                            for n, d in batch])
            revision, committed_batches = response.oid, committed_batches + 1
            write_receipt('uploading; ' + ('catalogue' if catalogue_scope else 'archive manifest') + ' may be pending')
            if not judge_scope and number < len(planned_batches):
                # Stop before the manifest if HF stored a transcript as LFS, added a rule or anything
                # else changed, so the Space stays detectably partly applied.
                verify(remote_files(api, repo, revision), revision, complete=False)
        final = api.repo_info(repo, repo_type='space', files_metadata=True)
        if not hf_visibility.unchanged(final, repo, 'space', revision):
            raise ValueError('Space changed before verification (or its visibility differs from the record); '
                             'inspect the latest revision')
        final_files = remote_files(api, repo, final.sha)
        attributes = verify(final_files, final.sha, complete=True)
    except Exception as error:
        try:
            write_receipt('failed: ' + type(error).__name__ + (': ' + str(error) if isinstance(error, ValueError) else ''))
        except Exception as receipt_error:  # never hide the original error
            print(f'Could not record the failure in the receipt {receipt}: {type(receipt_error).__name__}: '
                  f'{receipt_error}', file=sys.stderr)
        raise
    state = inventory(final_files)
    result.update(committed=committed_batches > 0, final_revision=revision, committed_batches=committed_batches,
                  status='verified', verification={
                      'against_revision': origin_revision, 'final_files': len(final_files),
                      'uploaded_files': len(uploads) + len(root_uploads),
                      'replaced_files': sum(n in expected and not same(origin_files[n], state[n]) for n in origin_files),
                      'added_files': len(added), 'verified_planned_files': len(expected),
                      'verified_preserved_files': len(set(origin_files) - set(expected)
                                                      - ({ATTRIBUTES} if judge_scope else set())),
                      'gitattributes': attributes, **({} if catalogue_scope else {'catalogue': 'unchanged'})})
    write_receipt('verified')
    return result


